CREATE TABLE accounts (
    id UUID PRIMARY KEY,
    login_name VARCHAR(128) NOT NULL UNIQUE,
    role VARCHAR(32) NOT NULL CHECK (role IN ('REPORTER', 'RESPONDER', 'ADMINISTRATOR')),
    status VARCHAR(32) NOT NULL CHECK (status IN ('ENABLED', 'DISABLED', 'DELETED')),
    version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE account_credentials (
    account_id UUID PRIMARY KEY REFERENCES accounts(id),
    password_hash VARCHAR(255) NOT NULL,
    temporary BOOLEAN NOT NULL DEFAULT FALSE,
    expires_at TIMESTAMPTZ NULL
);

CREATE TABLE audit_events (
    sequence BIGSERIAL PRIMARY KEY,
    id UUID NOT NULL UNIQUE,
    occurred_at TIMESTAMPTZ NOT NULL,
    actor_account_id UUID NULL,
    actor_role VARCHAR(32) NOT NULL,
    action VARCHAR(96) NOT NULL,
    target_type VARCHAR(64) NOT NULL,
    target_identifier VARCHAR(255) NOT NULL,
    outcome VARCHAR(32) NOT NULL,
    details JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE TABLE application_settings (
    setting_key VARCHAR(96) PRIMARY KEY,
    setting_value VARCHAR(255) NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE SPRING_SESSION (
    PRIMARY_ID CHAR(36) NOT NULL,
    SESSION_ID CHAR(36) NOT NULL,
    CREATION_TIME BIGINT NOT NULL,
    LAST_ACCESS_TIME BIGINT NOT NULL,
    MAX_INACTIVE_INTERVAL INT NOT NULL,
    EXPIRY_TIME BIGINT NOT NULL,
    PRINCIPAL_NAME VARCHAR(128),
    CONSTRAINT SPRING_SESSION_PK PRIMARY KEY (PRIMARY_ID)
);

CREATE UNIQUE INDEX SPRING_SESSION_IX1 ON SPRING_SESSION (SESSION_ID);
CREATE INDEX SPRING_SESSION_IX2 ON SPRING_SESSION (EXPIRY_TIME);
CREATE INDEX SPRING_SESSION_IX3 ON SPRING_SESSION (PRINCIPAL_NAME);

CREATE TABLE SPRING_SESSION_ATTRIBUTES (
    SESSION_PRIMARY_ID CHAR(36) NOT NULL,
    ATTRIBUTE_NAME VARCHAR(200) NOT NULL,
    ATTRIBUTE_BYTES BYTEA NOT NULL,
    CONSTRAINT SPRING_SESSION_ATTRIBUTES_PK PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
    CONSTRAINT SPRING_SESSION_ATTRIBUTES_FK FOREIGN KEY (SESSION_PRIMARY_ID)
        REFERENCES SPRING_SESSION(PRIMARY_ID) ON DELETE CASCADE
);
